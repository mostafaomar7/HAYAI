const DICTS: Record<SiteLocale, Record<SiteStringKey, string>> = { en, ar };

export function siteT(locale: SiteLocale, key: SiteStringKey, n?: string | number): string {
  const text = DICTS[locale]?.[key] ?? en[key];
  return n === undefined ? text : text.replace('{n}', String(n));
}
